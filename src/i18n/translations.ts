import type { Language } from './index'

let currentLang: Language = (typeof localStorage !== 'undefined' ? (localStorage.getItem('pdx_lang') as Language) : null) || 'en'

export function getLanguage(): Language {
  return currentLang
}

export function setLanguage(lang: Language) {
  currentLang = lang
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('pdx_lang', lang)
  }
}

